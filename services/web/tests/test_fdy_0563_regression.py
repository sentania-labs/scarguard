class TestResolveParamsACL:
    """Test shared/redis_client._resolve_params with per-service ACL users."""

    def test_resolve_params_no_user_uses_admin_password(self) -> None:
        """Without redis_user, _resolve_params uses REDIS_PASSWORD."""
        from shared.redis_client import _resolve_params

        os.environ["REDIS_PASSWORD"] = "admin-pass"
        try:
            params = _resolve_params({"host": "redis", "port": 6379})
            assert params["host"] == "redis"
            assert params["port"] == 6379
            assert params["password"] == "admin-pass"
            assert "username" not in params
        finally:
            del os.environ["REDIS_PASSWORD"]

    def test_resolve_params_with_user_uses_service_password(self) -> None:
        """With redis_user, _resolve_params uses {USER}_REDIS_PASSWORD."""
        from shared.redis_client import _resolve_params

        os.environ["DETECTOR_REDIS_PASSWORD"] = "detector-pass"
        try:
            params = _resolve_params(
                {"host": "redis", "port": 6379},
                redis_user="detector",
            )
            assert params["host"] == "redis"
            assert params["username"] == "detector"
            assert params["password"] == "detector-pass"
        finally:
            del os.environ["DETECTOR_REDIS_PASSWORD"]

    def test_resolve_params_fallback_to_admin(self) -> None:
        """If service-specific password is not set, fall back to REDIS_PASSWORD."""
        from shared.redis_client import _resolve_params

        os.environ["REDIS_PASSWORD"] = "admin-pass"
        try:
            params = _resolve_params(
                {"host": "redis", "port": 6379},
                redis_user="detector",
            )
            assert params["username"] == "detector"
            assert params["password"] == "admin-pass"
        finally:
            del os.environ["REDIS_PASSWORD"]


