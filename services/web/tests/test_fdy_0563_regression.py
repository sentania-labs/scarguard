class TestEventSigningChannelBound:
    """Exercise event_signing code paths with ACL-relevant scenarios."""

    def test_channel_bound_prevents_replay(self) -> None:
        """An event signed for channel A cannot be used on channel B."""
        from shared.event_signing import (
            CHANNEL_FIELD,
            sign_event,
            verify_event,
            derive_channel_key,
        )

        key = b"0" * 32
        event = {"camera_name": "pond", "class_name": "heron"}

        signed_a = sign_event(event, key, channel="channel-a")
        signed_b = sign_event(event, key, channel="channel-b")

        assert signed_a[CHANNEL_FIELD] == "channel-a"
        assert signed_b[CHANNEL_FIELD] == "channel-b"

        assert verify_event(signed_a, key, channel="channel-a") is True
        assert verify_event(signed_a, key, channel="channel-b") is False

    def test_channel_key_derivation_is_deterministic(self) -> None:
        """derive_channel_key produces same key for same inputs."""
        from shared.event_signing import derive_channel_key

        key = b"base-key-16-bytes!!"
        ch_key = derive_channel_key(key, "detections")
        assert ch_key == derive_channel_key(key, "detections")
        assert ch_key != derive_channel_key(key, "other")


