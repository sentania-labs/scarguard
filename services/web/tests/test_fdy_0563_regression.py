def _generate_passwords_for_test(admin_password: str) -> dict[str, str]:
    """Helper to generate passwords for testing without writing to /data."""
    import base64
    import os as _os
    import tempfile

    passwords: dict[str, str] = {}
    from shared.acl_init import _SERVICE_ACL
    for username, _, _, _ in _SERVICE_ACL:
        passwords[username] = base64.b64encode(_os.urandom(32)).decode("ascii")

    # Write ACL file to temp dir for testing
    acl_path = tempfile.mktemp(suffix=".acl.txt")
    try:
        content = _generate_acl_content(admin_password)
        with open(acl_path, "w") as f:
            f.write(content)

        # Read back and verify
        with open(acl_path) as f:
            read_content = f.read()
        assert admin_password in read_content
    finally:
        try:
            _os.unlink(acl_path)
        except OSError:
            pass

    return passwords


def _generate_acl_content(admin_password: str) -> str:
    """Reproduce the ACL content generation for testing."""
    from shared.acl_init import _SERVICE_ACL
    import base64
    import os

    lines: list[str] = [
        "# Auto-generated by Scarguard Redis ACL migration",
        "",
        f"user default on >{admin_password} ~* +@all",
        "",
    ]
    for username, cmds, keys, channels in _SERVICE_ACL:
        pw = base64.b64encode(os.urandom(32)).decode("ascii")
        cmd_str = " ".join(cmds)
        key_str = " ".join(f"&{k}" for k in keys)
        ch_str = " ".join(f"&{k}" for k in channels)
        lines.append(f"user {username} on >{pw} {cmd_str} {key_str} {ch_str}")
        lines.append("")

    return "\n".join(lines)


