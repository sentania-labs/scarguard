"""Regression test for FDY-0563: per-service Redis ACL access control.

This test exercises the actual shared modules (acl_init, redis_client,
rate_limit, event_signing, activation_lease) with mocked Redis connections
to verify that:

1. The shared/redis_client._resolve_params correctly handles redis_user.
2. The shared/acl_init module defines correct ACL users.
3. The web service's rate limiter connects with the correct parameters.
4. Services use their own credentials in docker-compose environment.
5. The shared reconnect_loop accepts redis_user parameter.
6. Event signing is channel-bound (prevents replay across channels).

The test covers code paths that were previously untested: ACL user
authentication paths in _resolve_params, and the ACL user definitions
themselves.

Real Redis ACL validation cannot be performed here because the worker
does not have a redis-server binary. In production, these ACL definitions
are applied via the Redis ACL file generated by the startup migration
procedure.
"""

