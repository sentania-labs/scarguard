class TestDockerComposeEnvs:
    """Verify docker-compose.yml uses per-service REDIS_PASSWORD where needed."""

    def test_compose_has_service_password_env_vars(self) -> None:
        """Each service should reference its own REDIS_PASSWORD env var."""
        with open("/crucible/repo/docker-compose.yml") as f:
            content = f.read()

        # All services that connect to Redis should use a REDIS_PASSWORD var
        expected_services = [
            "detector", "web", "notifier", "deterrent",
            "off-watchdog", "backup", "log-streamer",
            "training-controller", "trainer", "config-api",
        ]
        for svc in expected_services:
            # Find the service key line, then grab all text between it and
            # the next top-level service key (two-space indent + word).
            pattern = rf"^  {re.escape(svc)}:\n(.+?)\n  [a-z]"
            match = re.search(pattern, content, re.DOTALL | re.MULTILINE)
            if not match:
                # Last service in file, no next key to bound it.
                pattern2 = rf"^  {re.escape(svc)}:\n(.*)"
                match2 = re.search(pattern2, content, re.DOTALL)
                section = match2.group(1) if match2 else ""
            else:
                section = match.group(1)
            assert "REDIS_PASSWORD" in section, (
                f"Service '{svc}' missing REDIS_PASSWORD environment variable"
            )


